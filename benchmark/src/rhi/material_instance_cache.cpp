MaterialInstanceCache::~MaterialInstanceCache() {
    // Destroy instances first (they reference the base materials).
    clear_instances();
    if (lit_material_) engine_.destroy(lit_material_);
    if (lit_twosided_material_) engine_.destroy(lit_twosided_material_);
    if (lit_doublesided_material_) engine_.destroy(lit_doublesided_material_);
    if (unlit_material_) engine_.destroy(unlit_material_);
    if (glass_material_) engine_.destroy(glass_material_);
    if (clearcoat_material_) engine_.destroy(clearcoat_material_);
    if (aniso_material_) engine_.destroy(aniso_material_);
    if (subsurface_material_) engine_.destroy(subsurface_material_);
    if (cloth_material_) engine_.destroy(cloth_material_);
    if (foliage_shadow_material_) engine_.destroy(foliage_shadow_material_);
    if (colored_penumbra_material_) engine_.destroy(colored_penumbra_material_);
    if (window_material_) engine_.destroy(window_material_);
}

void MaterialInstanceCache::clear_instances() {
    lamp_emission_bindings_.clear();
    for (auto& [key, mi] : mat_instance_cache_) {
        engine_.destroy(mi);
    }
    mat_instance_cache_.clear();
    workflow_eligibility_.clear();
    compatibility_surfaces_ = 0;
    experimental_surfaces_ = 0;
    compatibility_instances_ = 0;
    experimental_instances_ = 0;
    refraction_unavailable_warned_ = false;
    clear_coat_rejected_warned_ = false;
    subsurface_unavailable_warned_ = false;
}

void MaterialInstanceCache::update_lamp_emission(float time_of_day) {
    const float gain = night_luminaire_gain(time_of_day);
    if (gain == lamp_emission_gain_) return;
    lamp_emission_gain_ = gain;
    for (const auto& binding : lamp_emission_bindings_) {
        binding.instance->setParameter("emissionScale", binding.nominal_scale * gain);
    }
}

Result<void> MaterialInstanceCache::load_base_materials() {
    lit_material_ = filament::Material::Builder()
        .package(k_heaven_lit_filamat, k_heaven_lit_filamat_size)
        .build(engine_);
    if (!lit_material_) {
        return std::unexpected(Error("Failed to load heaven_lit material"));
    }

    lit_twosided_material_ = filament::Material::Builder()
        .package(k_heaven_lit_twosided_filamat, k_heaven_lit_twosided_filamat_size)
        .build(engine_);
    if (!lit_twosided_material_) {
        return std::unexpected(Error("Failed to load heaven_lit_twosided material"));
    }

    std::printf("FilamentBackend: Materials loaded (lit + lit_twosided)\n");

    // Opaque double-sided lit base for two-sided non-alpha-tested surfaces
    // (cloth flags/banners). Best-effort: if it fails to load, get_or_create
    // falls back to the masked two-sided material so the surface still renders.
    lit_doublesided_material_ = filament::Material::Builder()
        .package(k_heaven_lit_doublesided_filamat, k_heaven_lit_doublesided_filamat_size)
        .build(engine_);
    if (!lit_doublesided_material_) {
        std::printf("  heaven_lit_doublesided material failed to load — "
                    "two-sided non-alpha surfaces fall back to masked two-sided\n");
    }

    unlit_material_ = filament::Material::Builder()
        .package(k_heaven_unlit_filamat, k_heaven_unlit_filamat_size)
        .build(engine_);
    if (!unlit_material_) {
        return std::unexpected(Error("Failed to load heaven_unlit material"));
    }

    // ── Refractive glass base material  ──────────
    // The screen-space refractive material glass surfaces route to when the
    // refraction feature is enabled. Authored with `refractionMode:
    // screenspace` / `refractionType: solid` in heaven_glass.mat, embedded
    // via gen_materials_data.py (never hand-edited). Loading it always — even
    // when --refraction is off — keeps base-material setup deterministic; the
    // routing in get_or_create() is what gates its use, so an off feature
    // never binds it and the Shipping_Look is preserved.
    glass_material_ = filament::Material::Builder()
        .package(k_heaven_glass_filamat, k_heaven_glass_filamat_size)
        .build(engine_);
    if (!glass_material_) {
        return std::unexpected(Error("Failed to load heaven_glass material"));
    }

    // ──  advanced base materials (Group A) ──────
    // One base material per Filament shading model the Material_Model_Selector
    // can pick. Loaded unconditionally — even when the advanced features are
    // off — so base-material setup stays deterministic; the selector in
    // get_or_create() is what gates their use, so a disabled feature never
    // binds them and the Shipping_Look is preserved.
    clearcoat_material_ = filament::Material::Builder()
        .package(k_heaven_lit_clearcoat_filamat, k_heaven_lit_clearcoat_filamat_size)
        .build(engine_);
    if (!clearcoat_material_) {
        return std::unexpected(Error("Failed to load heaven_lit_clearcoat material"));
    }

    aniso_material_ = filament::Material::Builder()
        .package(k_heaven_lit_aniso_filamat, k_heaven_lit_aniso_filamat_size)
        .build(engine_);
    if (!aniso_material_) {
        return std::unexpected(Error("Failed to load heaven_lit_aniso material"));
    }

    subsurface_material_ = filament::Material::Builder()
        .package(k_heaven_subsurface_filamat, k_heaven_subsurface_filamat_size)
        .build(engine_);
    if (!subsurface_material_) {
        return std::unexpected(Error("Failed to load heaven_subsurface material"));
    }

    cloth_material_ = filament::Material::Builder()
        .package(k_heaven_cloth_filamat, k_heaven_cloth_filamat_size)
        .build(engine_);
    if (!cloth_material_) {
        return std::unexpected(Error("Failed to load heaven_cloth material"));
    }

    std::printf("FilamentBackend: Advanced materials loaded "
                "(clearcoat + aniso + subsurface + cloth)\n");

    // ── Transparent foliage-shadow caster (Group B) ──────
    // The coverage-modulated (screen-door) transparent-shadow material foliage
    // casters route to when set_transparent_shadows(true). Loaded
    // unconditionally — even when --transparent-shadows is off — so
    // base-material setup stays deterministic; the routing in get_or_create()
    // gates its use, so a disabled feature never binds it and foliage keeps the
    // Shipping_Look opaque-silhouette path.
    foliage_shadow_material_ = filament::Material::Builder()
        .package(k_heaven_foliage_shadow_filamat, k_heaven_foliage_shadow_filamat_size)
        .build(engine_);
    if (!foliage_shadow_material_) {
        return std::unexpected(Error("Failed to load heaven_foliage_shadow material"));
    }

    std::printf("FilamentBackend: Foliage-shadow material loaded\n");

    // ── Colored-penumbra lit variant (Group B) ───────────
    // heaven_lit authored with `coloredPenumbra: true` — the only material
    // that compiles in the HAS_COLORED_PENUMBRA tint block (via the committed
    // define fix) and is built against the epsilon-clamped lib/filament
    // colored-penumbra shader (firefly-free on near-white surfaces).
    // Loaded unconditionally — even when --colored-penumbra is off — so
    // base-material setup stays deterministic; the routing in get_or_create()
    // gates its use, so a disabled feature never binds it and plain lit
    // surfaces keep heaven_lit (≤1/255 parity).
    colored_penumbra_material_ = filament::Material::Builder()
        .package(k_heaven_lit_colored_penumbra_filamat,
                 k_heaven_lit_colored_penumbra_filamat_size)
        .build(engine_);
    if (!colored_penumbra_material_) {
        return std::unexpected(Error("Failed to load heaven_lit_colored_penumbra material"));
    }

    std::printf("FilamentBackend: Colored-penumbra material loaded\n");

    // ── Window variant (opaque, glass-aware) ────────────────────
    // heaven_lit re-authored for Heaven's opaque, baked `*window*` wall
    // surfaces: the specular map drives a glass-aware microsurface (reflective
    // panes vs matte frame) and the night `_e` emission is tamed to a warm
    // interior glow instead of a clipped yellow card. Routed in get_or_create
    // when window_ref::is_window_material matches. Best-effort: if it fails to
    // load, windows fall back to the plain heaven_lit path unchanged.
    window_material_ = filament::Material::Builder()
        .package(k_heaven_window_filamat, k_heaven_window_filamat_size)
        .build(engine_);
    if (!window_material_) {
        std::printf("  heaven_window material failed to load — windows fall "
                    "back to the plain heaven_lit path\n");
    } else {
        std::printf("FilamentBackend: Window material loaded (heaven_window)\n");
    }

    return {};
}

bool MaterialInstanceCache::refraction_scene_color_available() const {
    // Production  availability check. Filament's screen-space
    // refraction samples the rendered scene-color buffer, which requires the
    // standard (FEATURE_LEVEL_1, GLES-3.0-class) feature set; FEATURE_LEVEL_0
    // backends (GLES 2.0) lack the color buffer the refractive path reads. On
    // every real desktop Vulkan/GL backend this is satisfied, so the gate
    // degrades to "always available". A gated smoke test overrides this to
    // force the unavailable branch.
    return engine_.getActiveFeatureLevel() >=
           filament::Engine::FeatureLevel::FEATURE_LEVEL_1;
}

filament::MaterialInstance* MaterialInstanceCache::get_or_create(
    const std::string& mesh_path,
    const std::string& surface_name,
    const GpuMaterial& gpu_mat,
    uint64_t usage_weight)
{
    return get_or_create_impl(mesh_path, surface_name, gpu_mat,
                              /*force_foliage_shadow=*/false, usage_weight);
}

filament::MaterialInstance* MaterialInstanceCache::get_or_create_foliage_shadow(
    const std::string& mesh_path,
    const std::string& surface_name,
    const GpuMaterial& gpu_mat)
{
    return get_or_create_impl(mesh_path, surface_name, gpu_mat,
                              /*force_foliage_shadow=*/true, 0);
}

filament::MaterialInstance* MaterialInstanceCache::get_or_create_impl(
    const std::string& mesh_path,
    const std::string& surface_name,
    const GpuMaterial& gpu_mat,
    bool force_foliage_shadow,
    uint64_t usage_weight)
{
    // Composite cache key: surface names recur across meshes, so the
    // (mesh_path, surface_name) pair is what keeps each surface's instance
    // distinct.
    const MaterialKey key{
        mesh_path,
        force_foliage_shadow ? (surface_name + "#foliage_shadow") : surface_name};

    // Check cache
    auto it = mat_instance_cache_.find(key);
    if (it != mat_instance_cache_.end()) {
        if (workflow_eligibility_[key]) {
            if (material_workflow_ ==
                MaterialWorkflow::SpecularGlossinessExperimental)
                experimental_instances_ += usage_weight;
            else
                compatibility_instances_ += usage_weight;
        }
        return it->second;
    }

    // ── Refractive-glass routing  ────────────────
    // A glass-flagged surface (classified from the xml0-derived material
    // name / parent chain) routes to the refractive glass material
    // when the refraction feature is enabled AND the screen-space scene color
    // it samples is available this frame. When the feature is off, or the
    // availability seam reports unavailable, we fall through to the
    // opaque heaven_lit path below so the surface pixel-matches the
    // Shipping_Look. Building once at scene-build time matches the
    // persistent-entity discipline; the seam latches a single diagnostic.
    if (gpu_mat.glass && refraction_enabled_ && glass_material_) {
        if (refraction_scene_color_available()) {
            if (auto* gmi = build_glass_instance(surface_name, gpu_mat)) {
                mat_instance_cache_[key] = gmi;
                return gmi;
            }
            // Glass instance build failed unexpectedly — fall through to the
            // opaque path so the surface still renders (degrade gracefully).
        } else if (!refraction_unavailable_warned_) {
            // screen-space scene color unavailable — render the
            // affected glass opaque for this build and emit ONE diagnostic.
            std::printf("  Refraction: screen-space scene color unavailable "
                        "— glass surfaces fall back to opaque heaven_lit\n");
            refraction_unavailable_warned_ = true;
        }
    }

    // Choose material: alpha-tested (masked foliage) vs two-sided-opaque
    // (cloth flags/banners) vs single-sided standard. A surface authored
    // two-sided but NOT alpha-tested must render OPAQUE and double-sided — the
    // masked two-sided material would cut its partial diffuse alpha into
    // see-through holes (the flag bug).

    // ── Advanced material-model selection (Group A) ─────
    // After the glass branch, the pure data-driven Material_Model_Selector
    // (engine/material_model_ref.h) resolves which Filament shading model this
    // surface renders with, from the xml0 surface/material name + parent chain
    // and the per-model enable gate carried in via set_advanced_models(). The
    // Shipping_Look base this surface resolves to today is Standard_Lit (the
    // lit / lit_twosided path below); with every advanced model disabled — or
    // no advanced marker matched — the selector returns Standard_Lit and the
    // existing base material + parameter writes are used unchanged.
    using material_model_ref::Material_Model;
    Material_Model model = material_model_ref::select_material_model(
        surface_name, gpu_mat.material_name, gpu_mat.parent_chain,
        Material_Model::Standard_Lit, advanced_models_);

    // Subsurface translucency samples the screen-space scene data the
    // translucency path needs; if that is unavailable, the affected surfaces
    // fall back to the opaque Shipping_Look material with ONE latched
    // diagnostic (mirroring the refraction availability seam in).
    if (model == Material_Model::Subsurface_Translucent &&
        !refraction_scene_color_available()) {
        if (!subsurface_unavailable_warned_) {
            std::printf("  Subsurface: screen-space scene data unavailable "
                        "— subsurface surfaces fall back to opaque heaven_lit\n");
            subsurface_unavailable_warned_ = true;
        }
        model = Material_Model::Standard_Lit;
    }

    // Map the selected model to the base material to instantiate. An advanced
    // model whose base material loaded replaces the Shipping_Look base; all
    // four advanced bases carry the full common lit parameter set (including
    // isMetallic), so the per-instance writes below apply uniformly. Standard_Lit
    // Unlit — or a missing advanced material — keeps the existing
    // two-sided-vs-standard lit choice unchanged (parity). NB: the
    // clear-coat / anisotropic bases are single-sided/opaque (they target
    // single-sided opaque metal: dragon/gear/engine/propeller/cannon). The
    // subsurface base is authored `doubleSided: true` + `blending: masked`
    // and the cloth base `doubleSided: true`, so foliage (subsurface) keeps
    // its two-sidedness + alpha cutout and fabric (cloth) renders both sides —
    // the reason those two `.mat` sources carry doubleSided/masked.
    const filament::Material* base_mat      = nullptr;
    bool                base_has_metallic = false;
    bool                base_supports_spec_gloss = false;
    switch (model) {
        case Material_Model::Clear_Coat:
            base_mat = clearcoat_material_;  base_has_metallic = true; break;
        case Material_Model::Anisotropic:
            base_mat = aniso_material_;      base_has_metallic = true; break;
        case Material_Model::Subsurface_Translucent:
            base_mat = subsurface_material_; base_has_metallic = true; break;
        case Material_Model::Cloth:
            base_mat = cloth_material_;      base_has_metallic = true; break;
        default: break;  // Standard_Lit / Unlit → Shipping_Look path below
    }
    if (!base_mat) {
        if (gpu_mat.alpha_ref > 0.0f) {
            // Alpha-tested foliage: masked, double-sided cutout silhouette.
            base_mat          = lit_twosided_material_;
            base_has_metallic = false;
            base_supports_spec_gloss = true;
        } else if (gpu_mat.two_sided) {
            // Two-sided but NOT alpha-tested (cloth flags/banners): opaque +
            // double-sided. Fall back to the masked two-sided material only if
            // the opaque double-sided base failed to load.
            base_mat          = lit_doublesided_material_ ? lit_doublesided_material_
                                                          : lit_twosided_material_;
            base_has_metallic = false;
            base_supports_spec_gloss = true;
        } else {
            base_mat          = lit_material_;
            base_has_metallic = true;
            base_supports_spec_gloss = true;
        }
        model             = Material_Model::Standard_Lit;
    }
    if (!base_mat) return nullptr;

    // ── Transparent foliage-shadow caster role (Group B) ───
    // Visible foliage must not use the transparent-shadow material: doing so
    // puts the tree/log alpha planes in Filament's transparent colour pass,
    // causing sorted-card flicker and semi-transparent billboard edges. The
    // scene builder instead asks for this forced role only for an extra
    // shadow-only duplicate renderable. That duplicate uses colorWrite:false
    // and transparentShadow:true, so it affects the shadow map but not the
    // colour/depth-stable visible foliage.
    if (force_foliage_shadow && foliage_shadow_material_) {
        base_mat          = foliage_shadow_material_;
        base_has_metallic = false;
        base_supports_spec_gloss = false;
        model             = Material_Model::Standard_Lit;
    }

    // ── Window routing (opaque, glass-aware) ────────────────────
    // Heaven's `*window*` surfaces are baked wall surfaces (NOT glass — the
    // glass classifier above deliberately excludes the `window` token). They
    // are ALPHA-MASKED (their diffuse alpha cuts the window's shape into the
    // wall), so the base-selection above routes them to the masked
    // lit_twosided_material_ — NOT lit_material_. Re-route both standard lit
    // bases to the dedicated heaven_window variant (itself masked + double-
    // sided, so the cutout is preserved), which makes the painted glass panes
    // reflective (via the spec map) and tames the night emission. Identified
    // purely from the xml0 material name / parent chain (window_material_ref.h
    // — no text mapping). Placed before the colored-penumbra block so windows
    // win over it. Best-effort: with no window material loaded the surface
    // keeps its Shipping_Look base unchanged.
    if (window_material_ && model == Material_Model::Standard_Lit &&
        (base_mat == lit_material_ || base_mat == lit_twosided_material_) &&
        window_ref::is_window_material(gpu_mat.material_name, gpu_mat.parent_chain)) {
        base_mat          = window_material_;
        base_has_metallic = true;  // heaven_window declares isMetallic (false for windows)
        base_supports_spec_gloss = true;
    }

    // ── Colored-penumbra routing (Group B) ───────────────
    // When the colored-penumbra feature is enabled, plain Standard_Lit
    // single-sided surfaces — the ones that fell through to the heaven_lit base
    // above, i.e. not glass (handled earlier), not an advanced shading model,
    // and not a foliage shadow caster (both of which already replaced base_mat)
    // — are built from the heaven_lit_colored_penumbra variant instead. That
    // variant is heaven_lit authored with `coloredPenumbra: true`, so it is
    // the ONLY material for which the committed HAS_COLORED_PENUMBRA define fix
    // emits the colored-penumbra tint block, compiled against the
    // epsilon-clamped lib/filament shader so near-white surfaces stay
    // firefly-free. The two-sided/alpha-tested lit path
    // (heaven_lit_twosided, foliage) is deliberately left untouched — the
    // variant is single-sided, matching heaven_lit. When the feature is
    // disabled the surface keeps heaven_lit, pixel-matching the Shipping_Look
    // The variant declares isMetallic (it is a copy of
    // heaven_lit), so base_has_metallic stays true as on the heaven_lit path.
    if (colored_penumbra_ && colored_penumbra_material_ &&
        base_mat == lit_material_ && model == Material_Model::Standard_Lit) {
        base_mat          = colored_penumbra_material_;
        base_has_metallic = true;
        base_supports_spec_gloss = false;
    }

    auto* mi = base_mat->createInstance();
    if (!mi) return nullptr;
    material_tuning::bind_standard_surface(*mi);
    if (base_mat == window_material_) {
        material_tuning::bind_window(*mi);
    }

    filament::TextureSampler sampler(
        filament::TextureSampler::MinFilter::LINEAR_MIPMAP_LINEAR,
        filament::TextureSampler::MagFilter::LINEAR,
        filament::TextureSampler::WrapMode::REPEAT);
    sampler.setAnisotropy(render_tuning::material_surface.texture_anisotropy);

    // Shared fallback textures for unassigned material slots.
    const filament::Texture* placeholder_tex_        = textures_.placeholder();
    const filament::Texture* placeholder_normal_tex_ = textures_.placeholder_normal();

    // ── Base color (diffuse) ────────────────────────────────────
    auto* diffuse_tex = textures_.get(gpu_mat.diffuse);
    mi->setParameter("hasBaseColor", diffuse_tex != nullptr);
    mi->setParameter("baseColorMap", diffuse_tex ? diffuse_tex : placeholder_tex_, sampler);

    // ── Normal map ──────────────────────────────────────────────
    auto* normal_tex = textures_.get(gpu_mat.normal);
    mi->setParameter("hasNormal", normal_tex != nullptr);
    mi->setParameter("normalMap", normal_tex ? normal_tex : placeholder_normal_tex_, sampler);

    // ── Specular map ────────────────────────────────────────────
    auto* spec_tex = textures_.get(gpu_mat.specular);
    mi->setParameter("hasSpecular", spec_tex != nullptr);
    mi->setParameter("specularMap", spec_tex ? spec_tex : placeholder_tex_, sampler);

    // ── Metal vs dielectric class ──────────────────────────────
    // The `isMetallic` flag comes from the parent-chain analysis
    // in the material DB; it's true only for materials descended
    // from `mesh_paint_reflection_cube_base` (or its tessellation
    // sibling), which are Heaven's marker for the cubemap-
    // reflective metal pipeline. The two-sided foliage material
    // doesn't take this parameter (foliage is always dielectric),
    // so we only set it on instances whose base material declares it
    // (heaven_lit + all four advanced bases; NOT heaven_lit_twosided).
    if (base_has_metallic) {
        mi->setParameter("isMetallic", gpu_mat.is_metallic);
    }
    if (base_supports_spec_gloss) {
        mi->setParameter(
            "specGlossWorkflow",
            material_workflow_ ==
                MaterialWorkflow::SpecularGlossinessExperimental);
        workflow_eligibility_[key] = true;
        if (material_workflow_ ==
            MaterialWorkflow::SpecularGlossinessExperimental) {
            ++experimental_surfaces_;
            experimental_instances_ += usage_weight;
        } else {
            ++compatibility_surfaces_;
            compatibility_instances_ += usage_weight;
        }
    }

    // ── Detail diffuse ──────────────────────────────────────────
    auto* detail_tex = textures_.get(gpu_mat.detail_diffuse);
    auto* detail_normal_tex = textures_.get(gpu_mat.detail_normal);
    auto* detail_spec_tex = textures_.get(gpu_mat.detail_specular);
    mi->setParameter("hasDetail", detail_tex != nullptr && gpu_mat.has_detail);
    mi->setParameter("detailMap", detail_tex ? detail_tex : placeholder_tex_, sampler);
    mi->setParameter("detailNormalMap",
                     detail_normal_tex ? detail_normal_tex : placeholder_normal_tex_, sampler);
    mi->setParameter("detailSpecularMap",
                     detail_spec_tex ? detail_spec_tex : placeholder_tex_, sampler);
    mi->setParameter("detailMode", static_cast<int32_t>(gpu_mat.detail_mode));
    mi->setParameter("detailStrength", filament::math::float3{
        gpu_mat.detail_strength[0],
        gpu_mat.detail_strength[1],
        gpu_mat.detail_strength[2]});
    mi->setParameter("detailUsesBaseAlpha", gpu_mat.alpha_ref <= 0.0f);
    mi->setParameter("detailTransform", filament::math::float4{
        gpu_mat.detail_transform[0], gpu_mat.detail_transform[1],
        gpu_mat.detail_transform[2], gpu_mat.detail_transform[3]});

    // ── Base UV transform ───────────────────────────────────────
    // Multiplied with UV0 in the shader as `uv*xy + zw` before
    // sampling diffuse/normal/spec/height. Defaults to identity
    // {1,1,0,0} when the material doesn't author one. See
    // GpuMaterial::base_transform for details.
    mi->setParameter("baseTransform", filament::math::float4{
        gpu_mat.base_transform[0], gpu_mat.base_transform[1],
        gpu_mat.base_transform[2], gpu_mat.base_transform[3]});

    // ── Height map ──────────────────────────────────────────────
    auto* height_tex = textures_.get(gpu_mat.height);
    mi->setParameter("hasHeight", height_tex != nullptr);
    mi->setParameter("heightMap", height_tex ? height_tex : placeholder_tex_, sampler);
    // Vertex displacement and every depth variant reconstruct an isotropic
    // filtered field, independent of fragment-detail anisotropy. Windows use
    // integer texel fetches to stay within their screen-space sampler budget.
    const filament::Texture* geometry_height_tex =
            height_tex ? height_tex : placeholder_tex_;
    if (base_mat == window_material_) {
        const int last_mip = std::max(1, static_cast<int>(geometry_height_tex->getLevels())) - 1;
        mi->setParameter("geometryHeightMaxLod", static_cast<float>(last_mip));
    } else {
        filament::TextureSampler geometry_height_sampler(
            filament::TextureSampler::MinFilter::LINEAR_MIPMAP_LINEAR,
            filament::TextureSampler::MagFilter::LINEAR,
            filament::TextureSampler::WrapMode::REPEAT);
        geometry_height_sampler.setAnisotropy(1.0f);
        mi->setParameter("geometryHeightMap", geometry_height_tex, geometry_height_sampler);
    }

    const auto displacement = geometry_displacement(
        gpu_mat, height_tex != nullptr,
        tessellation_scale_, tessellation_distance_multiplier_, tessellation_enabled_);
    mi->setParameter("geometryDisplacement", displacement.enabled);
    if (base_mat == lit_material_ ||
        base_mat == colored_penumbra_material_) {
        material_tuning::bind_ground_relief(*mi);
        mi->setParameter("groundReliefSurface",
                         gpu_mat.ground_relief_shading);
        mi->setParameter(
            "displacedSurfaceNormal",
            displacement.enabled && gpu_mat.displaced_surface_normal);
    }
    mi->setParameter("displacementParams", filament::math::float4{
        displacement.amplitude,
        displacement.power,
        displacement.fade.threshold,
        displacement.enabled ? displacement.fade.inverse_range() : 0.0f});

    // ── Tessellation map (POM displacement) ─────────────────────
    auto* tess_tex = textures_.get(gpu_mat.tessellation);

    // Displacement scale: tessellation maps use larger displacement (0.5)
    // than height maps (0.15), matching the original TCS/TES shader values
    float disp_scale = 0.0f;
    if (tess_tex) {
        disp_scale = render_tuning::material_surface.tessellation_pom_scale;
    } else if (height_tex) {
        disp_scale = render_tuning::material_surface.height_pom_scale;
    }
    mi->setParameter("displacementScale", disp_scale);

    // ── Per-instance advanced shading parameters (Group A) ──
    // Applied LAST so the common base-layer parameter writes above are
    // untouched. Only the parameters the SELECTED base material declares are
    // written, derived from Material_Data. Heaven authors none of Filament's
    // advanced shading parameters, so the strengths/tints are derived from the
    // model the selector assigned; the clear-coat strength is routed through
    // the pure clamp so a negative/NaN value is rejected.
    switch (model) {
        case Material_Model::Clear_Coat: {
            // Full lacquer layer over the base. Route the derived strength
            // through clamp_clear_coat_strength: a negative/NaN value is
            // rejected to a valid non-negative strength with ONE latched
            // diagnostic identifying the rejected value.
            const float raw_strength =
                render_tuning::advanced_material.clear_coat.x;
            const auto  clamped =
                material_model_ref::clamp_clear_coat_strength(raw_strength);
            if (clamped.rejected && !clear_coat_rejected_warned_) {
                std::printf("  Clear-coat: rejected out-of-range strength %.3f "
                            "— clamped to %.3f\n", raw_strength, clamped.value);
                clear_coat_rejected_warned_ = true;
            }
            mi->setParameter("clearCoat", clamped.value);
            mi->setParameter(
                "clearCoatRoughness",
                render_tuning::advanced_material.clear_coat.y);
            break;
        }
        case Material_Model::Anisotropic: {
            // Directional specular stretch along the surface tangent (+X in
            // tangent space, transformed by the surface TBN in the shader).
            mi->setParameter(
                "anisotropy", render_tuning::advanced_material.anisotropy);
            const auto direction =
                render_tuning::advanced_material.anisotropy_direction;
            mi->setParameter("anisotropyDirection",
                             filament::math::float3{
                                 direction.x, direction.y, direction.z});
            break;
        }
        case Material_Model::Subsurface_Translucent: {
            // Filament's subsurface model also uses subsurfaceColor as the
            // coloured penumbra term. Foliage must therefore stay green in
            // dense self-shadowed cards; a warm generic tint makes firs read
            // brown after the Filament material-version update.
            const bool foliage_like =
                material_model_ref::is_foliage_shadow_caster(
                    surface_name, gpu_mat.material_name, gpu_mat.parent_chain) ||
                surface_name.find("grass") != std::string::npos ||
                gpu_mat.material_name.find("grass") != std::string::npos;
            const auto color = foliage_like
                ? render_tuning::advanced_material.foliage_subsurface
                : render_tuning::advanced_material.generic_subsurface;
            mi->setParameter(
                "subsurfaceColor",
                filament::math::float3{color.x, color.y, color.z});
            mi->setParameter(
                "thickness", render_tuning::advanced_material.subsurface.x);
            mi->setParameter(
                "subsurfacePower", render_tuning::advanced_material.subsurface.y);
            break;
        }
        case Material_Model::Cloth: {
            // Charlie sheen f0 (dielectric-strength grazing sheen) with no
            // extra subsurface tint — the soft textile sheen of.
            const auto sheen = render_tuning::advanced_material.cloth_sheen;
            mi->setParameter("sheenColor",
                             filament::math::float3{sheen.x, sheen.y, sheen.z});
            mi->setParameter("subsurfaceColor",
                             filament::math::float3{0.0f, 0.0f, 0.0f});
            break;
        }
        default: break;  // Standard_Lit / Unlit — no advanced parameters
    }

    // ── Geometric specular anti-aliasing (Group B) ──
    // Applied to every glossy/metallic lit-model instance built here (the
    // lit / lit_twosided / advanced bases — this path never instantiates the
    // unlit material). The strength was resolved ONCE from the quality knob in
    // set_specular_aa (knob → heaven::spec_aa_strength → variance/threshold);
    // here we just push it through Filament's per-instance setters. The
    // materials are compiled with `specularAntiAliasing: true`, so these
    // setters take effect. When the feature is disabled we deliberately leave
    // them untouched so the instance keeps Filament's defaults and a flagless
    // run is pixel-identical to the Shipping_Look (≤1/255 parity).
    if (specular_aa_enabled_) {
        mi->setSpecularAntiAliasingVariance(specular_aa_variance_);
        mi->setSpecularAntiAliasingThreshold(specular_aa_threshold_);
    }

    // Cache and return
    bind_surface_emission(*mi, surface_name, gpu_mat, sampler, false);
    mat_instance_cache_[key] = mi;
    return mi;
}

void MaterialInstanceCache::bind_surface_emission(
    filament::MaterialInstance& instance,
    const std::string& surface_name,
    const GpuMaterial& gpu_mat,
    const filament::TextureSampler& sampler,
    bool refractive)
{
    const bool night_lamp = is_night_luminaire(surface_name);
    // Preserve the existing opaque glass fallback. The refractive route gains
    // synthetic emission only on actual enclosed bulbs, not arbitrary lab or
    // window glass. Authored emission sources remain valid on either route.
    const bool is_emitter = refractive
        ? night_lamp : surface_name.find("glass") != std::string::npos;
    auto* emissive_tex = textures_.get(gpu_mat.emission);
    bool has_emissive = emissive_tex != nullptr;
    if (refractive && !night_lamp && !gpu_mat.emission_light_source) {
        emissive_tex = nullptr;
        has_emissive = false;
    }

    // Bulbs without an emission map retain the existing diffuse fallback.
    // Torch handles are not bulb surfaces; their visible flame is a particle.
    if (!has_emissive && is_emitter) {
        if (auto* fallback = textures_.get(gpu_mat.diffuse)) {
            emissive_tex = fallback;
            has_emissive = true;
        }
    }
    instance.setParameter("hasEmissive", has_emissive);
    instance.setParameter("emissiveMap",
        emissive_tex ? emissive_tex : textures_.placeholder(), sampler);

    filament::math::float3 emit_tint{
        gpu_mat.emission_color[0],
        gpu_mat.emission_color[1],
        gpu_mat.emission_color[2]};
    float emit_scale = gpu_mat.emission_scale;
    if (is_emitter && has_emissive) {
        emit_scale = std::max(
            emit_scale, render_tuning::material_surface.forced_emission_scale);
        if (gpu_mat.emission_color[0] >= 0.999f &&
            gpu_mat.emission_color[1] >= 0.999f &&
            gpu_mat.emission_color[2] >= 0.999f) {
            // Preserve the established warm approximation, not a new angular
            // or blackbody model. A larger authored scale/tint has precedence.
            const auto tint = render_tuning::material_surface.forced_emission_tint;
            emit_tint = {tint.x, tint.y, tint.z};
        }
    }
    instance.setParameter("emissionTint", emit_tint);
    instance.setParameter("emissionScale",
        emit_scale * (night_lamp ? lamp_emission_gain_ : 1.0f));
    if (night_lamp) lamp_emission_bindings_.push_back({&instance, emit_scale});
}

filament::MaterialInstance* MaterialInstanceCache::build_glass_instance(
    const std::string& surface_name,
    const GpuMaterial& gpu_mat)
{
    // The refractive glass material (heaven_glass.mat) carries its
    // refractionMode/refractionType at compile time; here we only wire the
    // per-surface textures and the refraction set (transmission / absorption /
    // IOR / thickness / roughness). Filament resolves screen-space refraction
    // against the rendered scene color (gated by
    // refraction_scene_color_available() in get_or_create).
    if (!glass_material_) return nullptr;

    auto* mi = glass_material_->createInstance();
    if (!mi) return nullptr;
    material_tuning::bind_glass(*mi);

    filament::TextureSampler sampler(
        filament::TextureSampler::MinFilter::LINEAR_MIPMAP_LINEAR,
        filament::TextureSampler::MagFilter::LINEAR,
        filament::TextureSampler::WrapMode::REPEAT);
    sampler.setAnisotropy(render_tuning::material_surface.texture_anisotropy);

    const filament::Texture* placeholder_tex_        = textures_.placeholder();
    const filament::Texture* placeholder_normal_tex_ = textures_.placeholder_normal();

    // ── Base color (diffuse) ────────────────────────────────────
    auto* diffuse_tex = textures_.get(gpu_mat.diffuse);
    mi->setParameter("hasBaseColor", diffuse_tex != nullptr);
    mi->setParameter("baseColorMap", diffuse_tex ? diffuse_tex : placeholder_tex_, sampler);

    // ── Normal map ──────────────────────────────────────────────
    auto* normal_tex = textures_.get(gpu_mat.normal);
    mi->setParameter("hasNormal", normal_tex != nullptr);
    mi->setParameter("normalMap", normal_tex ? normal_tex : placeholder_normal_tex_, sampler);

    // ── Base UV transform ───────────────────────────────────────
    mi->setParameter("baseTransform", filament::math::float4{
        gpu_mat.base_transform[0], gpu_mat.base_transform[1],
        gpu_mat.base_transform[2], gpu_mat.base_transform[3]});

    // Emission is a surface property, so refractive routing must not bypass
    // the shared bulb map or its cached operating state.
    const auto emission_tuning = render_tuning::material_surface.emission;
    mi->setParameter("surfaceEmissionTuning", filament::math::float4{
        emission_tuning.x, emission_tuning.y, emission_tuning.z, emission_tuning.w});
    bind_surface_emission(*mi, surface_name, gpu_mat, sampler, true);

    // ── Glass tint + refraction set ─────────────────────────────
    // A lightly-tinted solid volume of window-glass IOR. Heaven authors no
    // refraction params, so these are the shared per-surface defaults for every
    // glass pane (building/lamp glass, the airship porthole, lab glassware).

    // Tuning note (airship porthole): a refractive pane over a DARK interior
    // (the porthole, lab glassware) refracts black and reads as a flat black
    // disc when transmission is near 1. The glass look on those has to come
    // from the REFLECTION, so transmission is pulled well below 1 here: that
    // lets the smooth dielectric surface (reflectance 0.5, sharp roughness)
    // carry a crisp sky/scene reflection across the curved dome instead of
    // showing the black interior. Clear panes with a bright scene behind still
    // read as glass — they just reflect a little more and transmit a little
    // less, which is what real glass does at a glancing dome angle anyway.
    return mi;
}

