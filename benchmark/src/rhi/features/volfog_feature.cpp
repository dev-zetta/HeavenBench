float halton2(uint32_t index) {
    float result = 0.0f;
    float scale = 0.5f;
    while (index > 0) {
        result += scale * static_cast<float>(index & 1u);
        index >>= 1u;
        scale *= 0.5f;
    }
    return result;
}

// 64×64  blue-noise tile generated by void-and-cluster. Provides
// per-pixel jitter for the volumetric fog ray-march start offset.
// We compute it once on startup from a deterministic Xorshift PRNG +
// a few iterations of relaxation toward a uniform spectral profile.
// Cheap (~1ms) and avoids shipping a binary asset.

// The result is good enough for our needs — TAA is averaging across
// 16 frames anyway, so the noise just needs to break banding within
// a single frame.
inline std::vector<uint8_t> generate_blue_noise_tile(int n) {
    std::vector<uint8_t> tile(static_cast<size_t>(n) * static_cast<size_t>(n));

    // Xorshift32 PRNG, seeded deterministically.
    uint32_t s = 0x12345678u;
    auto rnd = [&]() {
        s ^= s << 13; s ^= s >> 17; s ^= s << 5;
        return (s & 0xFFu);
    };
    for (auto& v : tile) v = static_cast<uint8_t>(rnd());

    // 4 passes of small-radius high-pass filter: subtract the local
    // average from each pixel, biasing the histogram back to uniform.
    // This is a poor man's void-and-cluster — produces noise that is
    // reasonably blue (low low-frequency power) without the textbook
    // implementation cost.
    auto at = [&](int x, int y) -> uint8_t& {
        return tile[((y % n + n) % n) * n + ((x % n + n) % n)];
    };
    for (int pass = 0; pass < 4; ++pass) {
        std::vector<uint8_t> out(tile.size());
        for (int y = 0; y < n; ++y) {
            for (int x = 0; x < n; ++x) {
                int sum =
                    at(x-1,y-1) + at(x,y-1) + at(x+1,y-1) +
                    at(x-1,y  ) + at(x,y  ) + at(x+1,y  ) +
                    at(x-1,y+1) + at(x,y+1) + at(x+1,y+1);
                int avg = sum / 9;
                int v = static_cast<int>(at(x, y)) - avg + 128;
                out[y * n + x] = static_cast<uint8_t>(std::clamp(v, 0, 255));
            }
        }
        tile = std::move(out);
    }
    return tile;
}

