void VolfogFeature::init(RenderContext& ctx, const AppConfig& config) {
    auto* engine_ = ctx.engine;

    // Load the volumetric fog material
    material_ = filament::Material::Builder()
        .package(k_heaven_volumetric_fog_filamat, k_heaven_volumetric_fog_filamat_size)
        .build(*engine_);
    if (!material_) {
        std::printf("  Volumetric fog: material failed to load\n");
        return;
    }

    // ── Blue-noise tile ─────────────────────────────────────────
    constexpr int NOISE_SIZE = render_tuning::volumetric_fog.noise_size;
    auto noise_data = generate_blue_noise_tile(NOISE_SIZE);
    auto* noise_buf = new uint8_t[noise_data.size()];
    std::memcpy(noise_buf, noise_data.data(), noise_data.size());

    noise_tex_ = filament::Texture::Builder()
        .width(NOISE_SIZE).height(NOISE_SIZE).levels(1)
        .sampler(filament::Texture::Sampler::SAMPLER_2D)
        .format(filament::Texture::InternalFormat::R8)
        .build(*engine_);

    filament::Texture::PixelBufferDescriptor pbd(
        noise_buf, noise_data.size(),
        filament::Texture::Format::R,
        filament::Texture::Type::UBYTE,
        [](void* p, size_t, void*) { delete[] static_cast<uint8_t*>(p); });
    noise_tex_->setImage(*engine_, 0, std::move(pbd));

    // ── Material instance with default parameters ───────────────
    mi_ = material_->createInstance();
    material_tuning::bind_volumetric_fog(*mi_);

    filament::TextureSampler depth_sampler(
        filament::TextureSampler::MinFilter::NEAREST,
        filament::TextureSampler::MagFilter::NEAREST,
        filament::TextureSampler::WrapMode::CLAMP_TO_EDGE);
    mi_->setParameter("depthTexture", ctx.resources->placeholder_depth_texture(), depth_sampler);

    filament::TextureSampler noise_sampler(
        filament::TextureSampler::MinFilter::NEAREST,
        filament::TextureSampler::MagFilter::NEAREST,
        filament::TextureSampler::WrapMode::REPEAT);
    mi_->setParameter("noiseTexture", noise_tex_, noise_sampler);

    mi_->setParameter("cameraPos", filament::math::float3{0.0f});
    mi_->setParameter("sunDir",   filament::math::float3{0.0f, 0.0f, 1.0f});
    mi_->setParameter("sunColor", filament::math::float3{1.0f});
    mi_->setParameter("sunVisible", false);

    // Default fog parameters. The shader uses **non-uniform step
    // spacing** (32 exponentially-distributed taps from 0 to
    // distLimit) so we can reach distant geometry without losing
    // detail near the camera. Clear noon density 0.0015 gives approximately
    // 93%/80%/69% transmittance at 50m/150m/250m before noise modulation.
    // update() blends back to the existing 0.005 night medium so local-light
    // scattering retains its balance. Lamp flux is soft-clipped per step.

    //   fogColor      — noon ambient scattering colour; update()
    //                   scales it with the scene's environment light.
    //   maxDistance   — ray-march cap. 250m so the airship and
    //                   castle in the open-vista views fade smoothly
    //                   instead of clamping to a single fog level.
    //   stepSize      — unused by the current shader (legacy
    //                   parameter from the uniform-stepping
    //                   variant); the exponential schedule is
    //                   computed from `distLimit` directly.
    //   intensity     — master scattering scale. With phase func
    //                   already 1/(4π) normalised, 1.0 produces
    //                   visible-but-subtle scattering.
    const auto medium = render_tuning::volumetric_fog.medium;
    const auto phase = render_tuning::volumetric_fog.phase;
    const auto color = render_tuning::volumetric_fog.color;
    mi_->setParameter("density", medium.x);
    mi_->setParameter("maxDistance", medium.y);
    mi_->setParameter("stepSize", medium.z);
    mi_->setParameter("miePhaseG", phase.x);
    mi_->setParameter("miePhaseGLight", phase.y);
    mi_->setParameter("intensity", medium.w);
    mi_->setParameter(
        "fogColor", filament::math::float3{color.x, color.y, color.z});
    mi_->setParameter("numLights", 0);
    mi_->setParameter("numLampVolumes", 0);
    // Initialise light arrays to all-zero. Filament requires arrays
    // to be set even if numLights=0, otherwise the underlying UBO
    // contains undefined data and SPIR-V validation rejects it.
    {
        filament::math::float4 zeros[MAX_LIGHTS]{};
        mi_->setParameter("lightPosRadius", zeros, MAX_LIGHTS);
        mi_->setParameter("lightColorIntensity", zeros, MAX_LIGHTS);
        mi_->setParameter("lampVolumePosRadius", zeros, MAX_LIGHTS);
        mi_->setParameter("lampVolumeColorGain", zeros, MAX_LIGHTS);
    }
    mi_->setParameter("time", 0.0f);
    mi_->setParameter("temporalJitter", 0.5f);

    // ── Fullscreen quad geometry (same shape as god-rays quad) ──
    struct QuadVertex {
        filament::math::float3 position;
        filament::math::float2 uv;
    };
    static QuadVertex quad_verts[] = {
        {{-1, -1, 0}, {0, 0}},
        {{ 1, -1, 0}, {1, 0}},
        {{ 1,  1, 0}, {1, 1}},
        {{-1,  1, 0}, {0, 1}},
    };
    static uint16_t quad_indices[] = { 0, 1, 2, 0, 2, 3 };

    vb_ = filament::VertexBuffer::Builder()
        .vertexCount(4)
        .bufferCount(2)
        .attribute(filament::VertexAttribute::POSITION, 0,
                   filament::VertexBuffer::AttributeType::FLOAT3,
                   0, sizeof(QuadVertex))
        .attribute(filament::VertexAttribute::UV0, 0,
                   filament::VertexBuffer::AttributeType::FLOAT2,
                   sizeof(filament::math::float3), sizeof(QuadVertex))
        .attribute(filament::VertexAttribute::TANGENTS, 1,
                   filament::VertexBuffer::AttributeType::SHORT4, 0, 0)
        .normalized(filament::VertexAttribute::TANGENTS)
        .build(*engine_);
    vb_->setBufferAt(*engine_, 0,
        filament::VertexBuffer::BufferDescriptor(quad_verts, sizeof(quad_verts)));

    static filament::math::short4 dummy_tangents[] = {
        {0, 0, 16383, 16383}, {0, 0, 16383, 16383},
        {0, 0, 16383, 16383}, {0, 0, 16383, 16383}
    };
    vb_->setBufferAt(*engine_, 1,
        filament::VertexBuffer::BufferDescriptor(dummy_tangents, sizeof(dummy_tangents)));

    ib_ = filament::IndexBuffer::Builder()
        .indexCount(6)
        .bufferType(filament::IndexBuffer::IndexType::USHORT)
        .build(*engine_);
    ib_->setBuffer(*engine_,
        filament::IndexBuffer::BufferDescriptor(quad_indices, sizeof(quad_indices)));

    // ── Renderable entity ───────────────────────────────────────

    // Priority 6: between scene geometry (priority 4 for opaques) and
    // god rays (priority 7). This way bloom (which Filament runs
    // automatically post-render) sees the in-scattered fog colour and
    // produces lamp halos through the haze; god rays composite on
    // top so the sun shafts remain crisp against the fog.
    entity_ = utils::EntityManager::get().create();
    filament::RenderableManager::Builder(1)
        .geometry(0, filament::RenderableManager::PrimitiveType::TRIANGLES,
                  vb_, ib_)
        .material(0, mi_)
        .castShadows(false)
        .receiveShadows(false)
        .culling(false)
        .priority(6)
        .boundingBox(uncullable_box())
        .build(*engine_, entity_);

    // Explicit transform component — Renderable doesn't add one
    // automatically, and update() needs one to position the quad in
    // front of the camera each frame.
    {
        auto& tcm = engine_->getTransformManager();
        tcm.create(entity_);
    }

    enabled_ = config.features.volumetric_fog;
    if (enabled_) {
        ctx.scene->addEntity(entity_);
        in_scene_ = true;
    }

    std::printf("  Volumetric fog: per-light ray-march initialized (%d-tap, %d lights max)%s\n",
                32, MAX_LIGHTS, enabled_ ? "" : " (disabled)");
}

void VolfogFeature::on_enabled_changed(RenderContext& ctx, bool on) {
    if (!entity_) return;
    if (on && !in_scene_) {
        ctx.scene->addEntity(entity_);
        in_scene_ = true;
    } else if (!on && in_scene_) {
        ctx.scene->remove(entity_);
        in_scene_ = false;
    }
}

void VolfogFeature::on_depth_prepass_begin(RenderContext& ctx) {
    if (entity_ && in_scene_) ctx.scene->remove(entity_);
}

void VolfogFeature::on_depth_prepass_end(RenderContext& ctx) {
    if (entity_ && in_scene_) ctx.scene->addEntity(entity_);
}

void VolfogFeature::release_shared_targets(RenderContext& ctx) {
    const filament::TextureSampler sampler(
        filament::TextureSampler::MinFilter::NEAREST,
        filament::TextureSampler::MagFilter::NEAREST,
        filament::TextureSampler::WrapMode::CLAMP_TO_EDGE);
    if (mi_) mi_->setParameter("depthTexture",
        ctx.resources->placeholder_depth_texture(), sampler);
    bound_depth_ = nullptr;
}

void VolfogFeature::update(RenderContext& ctx, const FrameContext& frame) {
    if (!mi_) return;
    auto* engine_ = ctx.engine;
    const Camera& camera = *frame.camera;
    const LightingParams& lighting = *frame.lighting;
    int viewport_w = frame.viewport_w;
    int viewport_h = frame.viewport_h;
    float time = frame.time;

    // Bind the shared depth pre-pass texture once it exists / on resize.
    if (frame.depth_texture && frame.depth_texture != bound_depth_) {
        filament::TextureSampler depth_sampler(
            filament::TextureSampler::MinFilter::NEAREST,
            filament::TextureSampler::MagFilter::NEAREST,
            filament::TextureSampler::WrapMode::CLAMP_TO_EDGE);
        mi_->setParameter("depthTexture", frame.depth_texture, depth_sampler);
        bound_depth_ = frame.depth_texture;
    }

    auto& lm = engine_->getLightManager();
    glm::vec3 cam = camera.position;
    const float aspect = safe_aspect(viewport_w, viewport_h);
    const glm::mat4 view_mat = camera.view_matrix();

    // Original lamp volumes are an analytic atmospheric glow, independent
    // of the optical-axis flare and of the medium's light-selection budget.
    // Keep the nearest visible spheres in fixed storage. A source's live
    // native power and position handle night scheduling, external shutoff,
    // retirement and floating-island motion without cached cosmetic state.
    struct VolumeCandidate {
        filament::math::float4 position_radius{};
        float gain = 0.0f;
        float distance = 0.0f;
    };
    std::array<VolumeCandidate, MAX_LIGHTS> volumes{};
    int volume_count = 0;
    const auto& fog_tuning = render_tuning::volumetric_fog;
    const float radius = fog_tuning.lamp_volume_radius;
    const glm::vec3 forward = -glm::vec3(view_mat[0][2], view_mat[1][2], view_mat[2][2]);
    const glm::vec3 right{view_mat[0][0], view_mat[1][0], view_mat[2][0]};
    const glm::vec3 up{view_mat[0][1], view_mat[1][1], view_mat[2][1]};
    const float tangent_y = std::tan(glm::radians(camera.fov * 0.5f));
    const float tangent_x = tangent_y * aspect;
    const std::array<glm::vec3, 5> inside_normals{
        forward, glm::normalize(forward * tangent_x + right),
        glm::normalize(forward * tangent_x - right),
        glm::normalize(forward * tangent_y + up),
        glm::normalize(forward * tangent_y - up)};
    for (const auto& light : frame.scene_lights) {
        if (!light.local_volume_source) continue;
        const auto li = lm.getInstance(light.entity);
        if (!li) continue;
        const float gain = lens_flare_power_gain(lm.getIntensity(li), light.nominal_intensity);
        if (gain <= 0.0f) continue;
        const auto position = lm.getPosition(li);
        const glm::vec3 offset = glm::vec3(position.x, position.y, position.z) - cam;
        const float distance = glm::length(offset);
        if (!std::isfinite(distance)) continue;
        // Touching/near-tangent spheres stay. This does not remove source
        // lights or shadow casters; it selects only cosmetic volume uniforms.
        const float reserve = std::max(
            1.0e-4f * std::max(distance, radius),
            distance * 2.0f * tangent_y / static_cast<float>(std::max(viewport_h, 1)));
        if (std::any_of(inside_normals.begin(), inside_normals.end(),
                [&](glm::vec3 normal) { return glm::dot(normal, offset) < -radius - reserve; }))
            continue;
        int slot = volume_count;
        if (slot == MAX_LIGHTS) {
            if (distance >= volumes.back().distance) continue;
            slot = MAX_LIGHTS - 1;
        } else {
            ++volume_count;
        }
        while (slot > 0 && distance < volumes[slot - 1].distance) {
            volumes[slot] = volumes[slot - 1];
            --slot;
        }
        volumes[slot] = {{position.x, position.y, position.z, radius}, gain, distance};
    }
    std::array<filament::math::float4, MAX_LIGHTS> volume_positions{};
    std::array<filament::math::float4, MAX_LIGHTS> volume_colors{};
    const auto volume_color = fog_tuning.lamp_volume_color;
    for (int i = 0; i < volume_count; ++i) {
        volume_positions[i] = volumes[i].position_radius;
        volume_colors[i] = {volume_color.x, volume_color.y, volume_color.z, volumes[i].gain};
    }
    mi_->setParameter("numLampVolumes", volume_count);
    mi_->setParameter("lampVolumePosRadius", volume_positions.data(), MAX_LIGHTS);
    mi_->setParameter("lampVolumeColorGain", volume_colors.data(), MAX_LIGHTS);

    // Score every scene light entity. We score by `falloff_radius /
    // distance` so lights whose visible reach extends near the camera
    // win regardless of their absolute lumens — that's what we
    // actually care about for fog scattering. Lights beyond their own
    // falloff radius cannot contribute to fog, so they get pruned.
    struct Candidate {
        utils::Entity e;
        float         score;
    };
    std::vector<Candidate> cand;
    cand.reserve(frame.scene_light_entities.size() + 1);

    for (auto ent : frame.scene_light_entities) {
        auto li = lm.getInstance(ent);
        if (!li) continue;
        // Use the LightManager getters — both classes of lights store
        // their world position there, and floating-island animations
        // already updated those before this frame.
        auto p = lm.getPosition(li);
        glm::vec3 pos{p.x, p.y, p.z};
        float falloff = lm.getFalloff(li);
        float d = glm::distance(pos, cam);
        if (d > falloff * render_tuning::volumetric_fog.light_reach_multiplier)
            continue;
        float score = falloff / std::max(
            d, render_tuning::volumetric_fog.minimum_light_distance);
        cand.push_back({ent, score});
    }

    // Partial sort to find the top MAX_LIGHTS by score.
    int picked = std::min<int>(MAX_LIGHTS, static_cast<int>(cand.size()));
    if (picked > 0) {
        std::partial_sort(cand.begin(), cand.begin() + picked, cand.end(),
            [](const Candidate& a, const Candidate& b) { return a.score > b.score; });
    }

    // Pack into the float4 arrays. Filament requires the whole array
    // to be set in a single call, so we build a contiguous staging
    // buffer and submit it once. Empty slots stay at zero so the
    // shader's `for (k < numLights)` early-out never reads them.
    filament::math::float4 pos_radius_buf[MAX_LIGHTS]{};
    filament::math::float4 color_intensity_buf[MAX_LIGHTS]{};
    for (int i = 0; i < picked; ++i) {
        auto li = lm.getInstance(cand[i].e);
        if (!li) continue;
        auto p = lm.getPosition(li);
        auto c = lm.getColor(li);
        float falloff = lm.getFalloff(li);
        float intensity = lm.getIntensity(li);

        // Punctual-light getIntensity returns candela, after Filament converts
        // the builder's lumen input. Normalize live source power by the artistic
        // reference below; this is neither a lumen value nor a physical fog
        // transport model. Lamp power changes also affect local inscatter, so
        // review the full night scene rather than only its illuminated surfaces.
        float flux = intensity /
            render_tuning::volumetric_fog.light_flux_reference;

        pos_radius_buf[i] = {p.x, p.y, p.z, falloff};
        color_intensity_buf[i] = {c.r, c.g, c.b, flux};
    }
    mi_->setParameter("lightPosRadius", pos_radius_buf, MAX_LIGHTS);
    mi_->setParameter("lightColorIntensity", color_intensity_buf, MAX_LIGHTS);
    mi_->setParameter("numLights", picked);

    // Camera ray origin. The view-ray direction is reconstructed in
    // the shader from the quad's own world position, so the fog no
    // longer needs an inverse view-projection matrix; the march length
    // is clamped at the linear scene depth instead.
    mi_->setParameter("cameraPos",
        filament::math::float3{cam.x, cam.y, cam.z});
    mi_->setParameter("sunDir",
        filament::math::float3{lighting.sun_dir.x, lighting.sun_dir.y, lighting.sun_dir.z});

    // Sun colour in fog is the actual photon flux ÷ a flux-to-fog
    // factor so the haze gets a sun tint without over-lighting the
    // scene. The sun's lux scale is enormous (~110000 at noon) so we
    // gate by intensity; below ~5000 lux the sun isn't really
    // contributing to fog scattering at all.
    bool sun_visible =
        lighting.sun_intensity > render_tuning::volumetric_fog.sun_min_lux;
    mi_->setParameter("sunVisible", sun_visible);
    if (sun_visible) {
        float sun_flux = lighting.sun_intensity /
            render_tuning::volumetric_fog.sun_flux_reference;
        mi_->setParameter("sunColor", filament::math::float3{
            lighting.sun_color.x * sun_flux,
            lighting.sun_color.y * sun_flux,
            lighting.sun_color.z * sun_flux});
    }

    // This unlit material receives already-normalized scattering radiance,
    // so a constant noon tint would glow equally brightly at midnight.
    // Follow absolute ambient illumination with a fixed radiance reference.
    // Renormalizing by the current noon tuning would brighten the night fog
    // whenever daytime environment lighting is reduced.
    const auto& environment = render_tuning::lighting;
    const float daylight = std::max(0.0f, lighting.sun_intensity) /
        environment.reference_sun_lux;
    const auto& fog = render_tuning::volumetric_fog;
    mi_->setParameter("density", std::lerp(
        fog.medium.x, fog.day_density, std::clamp(daylight, 0.0f, 1.0f)));
    const float ambient_scale =
        (environment.environment_floor_lux +
         daylight * environment.environment_day_span_lux) /
        render_tuning::volumetric_fog.ambient_reference_lux;
    const auto fog_color = render_tuning::volumetric_fog.color;
    mi_->setParameter("fogColor", filament::math::float3{
        fog_color.x * ambient_scale,
        fog_color.y * ambient_scale,
        fog_color.z * ambient_scale});

    mi_->setParameter("time", time);
    const uint32_t sampling_frame = frame.capture_frame
        ? static_cast<uint32_t>(*frame.capture_frame & 1023u) : frame_index_++;
    mi_->setParameter("temporalJitter", halton2((sampling_frame & 1023u) + 1u));

    // Position the fullscreen quad just inside the far plane (same
    // trick as god rays). The fragment shader uses the depth buffer
    // for the actual ray length; this just makes sure every screen
    // pixel runs the fragment shader.
    glm::vec3 cam_pos = camera.position;
    glm::vec3 cam_fwd = -glm::vec3(view_mat[0][2], view_mat[1][2], view_mat[2][2]);
    glm::vec3 cam_right = glm::vec3(view_mat[0][0], view_mat[1][0], view_mat[2][0]);
    glm::vec3 cam_up = glm::vec3(view_mat[0][1], view_mat[1][1], view_mat[2][1]);

    float dist = render_tuning::fullscreen.volumetric_fog_distance;
    float half_h = dist * std::tan(glm::radians(
        camera.fov * 0.5f));
    float half_w = half_h * aspect;
    glm::vec3 center = cam_pos + cam_fwd * dist;

    glm::mat4 quad_xform(1.0f);
    quad_xform[0] = glm::vec4(cam_right * half_w, 0.0f);
    quad_xform[1] = glm::vec4(cam_up * half_h, 0.0f);
    quad_xform[2] = glm::vec4(cam_fwd, 0.0f);
    quad_xform[3] = glm::vec4(center, 1.0f);

    auto& tcm = engine_->getTransformManager();
    auto ti = tcm.getInstance(entity_);
    if (ti) {
        tcm.setTransform(ti, glm_to_filament(quad_xform));
    }
}

void VolfogFeature::destroy(RenderContext& ctx) {
    auto* engine_ = ctx.engine;
    if (entity_) {
        if (in_scene_) ctx.scene->remove(entity_);
        engine_->destroy(entity_);
        utils::EntityManager::get().destroy(entity_);
        entity_ = {};
    }
    if (mi_) { engine_->destroy(mi_); mi_ = nullptr; }
    if (material_) { engine_->destroy(material_); material_ = nullptr; }
    if (vb_) { engine_->destroy(vb_); vb_ = nullptr; }
    if (ib_) { engine_->destroy(ib_); ib_ = nullptr; }
    if (noise_tex_) { engine_->destroy(noise_tex_); noise_tex_ = nullptr; }
}

