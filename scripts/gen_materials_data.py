#!/usr/bin/env python3
"""Embed unchanged .filamat bytes in materials_data.cpp with a small public header."""
from __future__ import annotations

import filecmp
import os
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATERIALS_DIR = os.path.join(REPO_ROOT, "benchmark", "materials")
OUTPUT_FILE = os.path.join(REPO_ROOT, "benchmark", "src", "rhi", "materials_data.h")
OUTPUT_SOURCE = os.path.join(REPO_ROOT, "benchmark", "src", "rhi", "materials_data.cpp")

MATERIALS = [
    "heaven_lit",
    "heaven_lit_twosided",
    "heaven_lit_doublesided",
    "heaven_unlit",
    "heaven_lit_clearcoat",
    "heaven_lit_aniso",
    "heaven_lit_colored_penumbra",
    "heaven_window",
    "heaven_subsurface",
    "heaven_cloth",
    "heaven_foliage_shadow",
    "heaven_grass",
    "heaven_godrays",
    "heaven_clouds",
    "heaven_smoke",
    "heaven_sky",
    "heaven_volumetric_fog",
    "heaven_blit",
    "heaven_heat_haze",
    "heaven_debug_arrow",
    "heaven_flame",
    "heaven_glow",
    "heaven_lens_flare",
    "heaven_firefly",
    "heaven_rain",
    "heaven_splash",
    "heaven_glass",
    "heaven_volumetric_clouds",
    "heaven_ssgi",
    "heaven_hdr_encode",
    "heaven_depth",
    "heaven_depth_masked",
    "heaven_grass_depth",
    "heaven_height_sample",
]


def main() -> int:
    materials = []
    missing = []
    for name in MATERIALS:
        path = os.path.join(MATERIALS_DIR, f"{name}.filamat")
        if not os.path.isfile(path):
            missing.append(path)
            continue
        with open(path, "rb") as f:
            data = f.read()
        if not data:
            print(f"error: compiled material is empty: {path}", file=sys.stderr)
            return 1
        materials.append((name, data))

    if missing:
        print("error: missing compiled materials (outputs left unchanged):", file=sys.stderr)
        for p in missing:
            print(f"  {p}", file=sys.stderr)

        return 1

    # Validate every input before touching either output. Stage complete files
    # beside their destinations, then replace each atomically. Identical files
    # retain their timestamps so regeneration does not force a rebuild.
    staged = []
    try:
        for destination in (OUTPUT_FILE, OUTPUT_SOURCE):
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", newline="\n", delete=False,
                dir=os.path.dirname(destination), prefix=".materials_data-",
            ) as output:
                staged.append((output.name, destination))
                output.write("// Auto-generated by scripts/gen_materials_data.py — do not edit by hand.\n")
                output.write("// Regenerate after modifying .mat files: ./scripts/build.sh --materials\n")
                if destination == OUTPUT_FILE:
                    output.write("#ifndef HEAVENBENCH_RHI_MATERIALS_DATA_H\n#define HEAVENBENCH_RHI_MATERIALS_DATA_H\n#include <cstdint>\n#include <cstddef>\n\n")
                    for name, data in materials:
                        output.write(f"extern const std::uint8_t k_{name}_filamat[{len(data)}];\n")
                        output.write(f"inline constexpr std::size_t k_{name}_filamat_size = sizeof(k_{name}_filamat);\n\n")
                    output.write("#endif // HEAVENBENCH_RHI_MATERIALS_DATA_H\n")
                else:
                    # The extern declarations give these const definitions
                    # external linkage without inline array bodies.
                    output.write('#include "materials_data.h"\n\n')
                    for index, (name, data) in enumerate(materials):
                        if index:
                            output.write("\n")
                        output.write(f"// {name} ({len(data)} bytes)\n")
                        output.write(f"const std::uint8_t k_{name}_filamat[{len(data)}] = {{\n")
                        for i in range(0, len(data), 16):
                            output.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
                        output.write("};\n")
                output.flush()
                os.fsync(output.fileno())
            os.chmod(output.name, 0o644)

        for temporary, destination in staged:
            if os.path.isfile(destination) and filecmp.cmp(temporary, destination, shallow=False):
                os.unlink(temporary)
                print(f"unchanged {destination}")
            else:
                os.replace(temporary, destination)
                print(f"wrote {destination} ({len(materials)} materials)")
    finally:
        for temporary, _ in staged:
            if os.path.exists(temporary):
                os.unlink(temporary)
    return 0


if __name__ == "__main__":
    sys.exit(main())
